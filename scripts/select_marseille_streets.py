"""Rank Marseille streets from the pinned OSM extract and write the deck's selection."""

import json
import math
import re
import unicodedata
from collections import defaultdict
from pathlib import Path

import yaml
from pyproj import Transformer
from shapely.geometry import LineString
from shapely.ops import unary_union

root = Path(__file__).resolve().parents[1]
data = root / "data/marseille"
rules = yaml.safe_load((data / "street-ranking.yml").read_text())
to_metres = Transformer.from_crs("EPSG:4326", "EPSG:2154", always_xy=True)
centre = to_metres.transform(*rules["centre"])
weights = rules["class_weights"]
excluded = re.compile(r"^(?:" + "|".join(map(re.escape, rules["exclude_prefixes"])) + r")\b")


def slug(text):
    ascii_text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", ascii_text.lower()).strip("-")


def display(name):
    # "Boulevard de la Libération - Général de Monsabert": keep the everyday name.
    return name.split(" - ")[0]


streets = defaultdict(list)
for way in json.loads((data / "osm-streets.json").read_text())["elements"]:
    tags = way["tags"]
    if "name" in tags and tags.get("area") != "yes":
        line = LineString([to_metres.transform(p["lon"], p["lat"]) for p in way["geometry"]])
        streets[tags["name"]].append((way["id"], tags["highway"].removesuffix("_link"), line))

candidates = {}
for name, ways in streets.items():
    # Parts closer than the gap form one street; distant parts are homonyms.
    clusters = unary_union([line.buffer(rules["homonym_gap_m"] / 2) for _, _, line in ways])
    clusters = list(getattr(clusters, "geoms", [clusters]))
    groups = [[w for w in ways if w[2].intersects(c)] for c in clusters]
    main = max(groups, key=lambda group: sum(w[2].length for w in group))
    total = sum(w[2].length for w in ways)
    length = sum(w[2].length for w in main)
    point = unary_union([w[2] for w in main]).centroid
    distance = math.hypot(point.x - centre[0], point.y - centre[1]) / 1000
    weight = max(weights.get(highway, 1) for _, highway, _ in main)
    candidates[name] = {
        "ways": sorted(w[0] for w in main),
        "length": length,
        "homonym": length < 0.8 * total,
        "score": weight * math.sqrt(length / 1000) / (1 + distance / rules["centre_km"]),
    }

missing = [name for name in rules["include"] if name not in candidates]
if missing:
    raise ValueError(f"Included streets absent from OSM: {missing}")
chosen = list(rules["include"])
ranked = sorted(candidates.items(), key=lambda item: -item[1]["score"])
for name, info in ranked:
    if len(chosen) >= rules["count"]:
        break
    if (
        name in chosen
        or name in rules["exclude_names"]
        or excluded.match(name)
        or info["homonym"]
        or info["length"] < rules["min_length_m"]
    ):
        continue
    chosen.append(name)

selection, catalog, ids = [], [], set()
for name in sorted(chosen, key=lambda n: -candidates[n]["score"]):
    key = "street-" + slug(display(name))
    if key in ids:
        raise ValueError(f"Duplicate street ID: {key}")
    ids.add(key)
    selection.append({"id": key, "osm_name": name, "ways": candidates[name]["ways"]})
    catalog.append({"id": key, "name": display(name), "view": "marseille"})
(data / "street-selection.yml").write_text(
    "# Generated by scripts/select_marseille_streets.py from street-ranking.yml.\n"
    + yaml.safe_dump({"streets": selection}, allow_unicode=True, sort_keys=False)
)
(root / "catalog/streets.yml").write_text(
    yaml.safe_dump({"features": catalog}, allow_unicode=True, sort_keys=False)
)
print(f"{len(selection)} streets selected")
